/**
 * Writes src/app/courseUniverse.generated.ts from the authored curriculum.
 *
 * WHY THIS IS GENERATED AND NOT DERIVED ON DEVICE. The mastery denominator is
 * the whole course (docs/ECONOMY.md), so progress.ts needs every topic of the
 * chosen course. Asking @blueberry/curriculum for that at runtime pulled the
 * entire authored corpus into the game route's entry chunk, because progress.ts
 * is reachable from the shell: the initial payload went from 176.4 KB gzipped to
 * 260.9 KB in one commit. The course graph is static content, so it is
 * precomputed here instead, the same rule CLAUDE.md already applies to CIP
 * labels: computed at authoring time, stored on the artifact, never derived on
 * device.
 *
 * Drift is caught, not trusted: test/courseUniverseGenerated.test.ts reads the
 * real curriculum and fails if this table disagrees with it. A red run there
 * means run this script, it does not mean edit the table by hand.
 *
 * Usage, from the repo root:
 *   npm run build
 *   node apps/web/scripts/gen-course-universe.mjs
 */
import { writeFile } from "node:fs/promises";
import path from "node:path";

const curriculum = await import("../../../packages/curriculum/dist/index.js");
const { ALL_COURSE_IDS, probeTopicIdsForCourse, topicDefinition } = curriculum;

const DEFAULT_DIFFICULTY = 3;

function difficultyFor(topic) {
  try {
    const definition = topicDefinition(topic);
    const own = definition.difficulty;
    return typeof own === "number" && own >= 1 && own <= 5 ? own : DEFAULT_DIFFICULTY;
  } catch {
    return DEFAULT_DIFFICULTY;
  }
}

const rows = ALL_COURSE_IDS.map((course) => {
  const nodes = probeTopicIdsForCourse(course).map((topic) => `    ["lesson:${topic}", ${difficultyFor(topic)}],`);
  return `  ${course}: [\n${nodes.join("\n")}\n  ],`;
}).join("\n");

const file = `/**
 * GENERATED by apps/web/scripts/gen-course-universe.mjs. Do not edit by hand.
 *
 * The mastery denominator, per course, as [nodeId, difficulty] pairs. The node
 * ids are what progress.ts journals on a clear, so the numerator and the
 * denominator cannot disagree about what a node is.
 *
 * It is a table rather than a call into @blueberry/curriculum because
 * progress.ts sits in the game route's entry chunk, and importing the corpus
 * there put the whole authored curriculum in front of every student.
 * test/courseUniverseGenerated.test.ts fails if this drifts from the corpus.
 */

export type GeneratedUniverseRow = readonly [nodeId: string, difficulty: 1 | 2 | 3 | 4 | 5];

export const COURSE_UNIVERSE: Readonly<Record<string, readonly GeneratedUniverseRow[]>> = Object.freeze({
${rows}
});
`;

const out = path.join(import.meta.dirname, "..", "src", "app", "courseUniverse.generated.ts");
await writeFile(out, file, "utf8");
console.log(`courseUniverse.generated.ts: ${ALL_COURSE_IDS.length} courses`);
